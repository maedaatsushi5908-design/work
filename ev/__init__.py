"""
ev — 期待値ベースの株式投資プロセス支援ライブラリ

「期待値の高い株は存在する」という前提は正しい。しかし個人投資家にとっての
本当の難所は、自分がそれを事前に識別できたかどうかを検証できない点にある。
このライブラリは以下の4層でその問題に対処する。

  1. universe   — 大口資金が構造的に入れない領域に的を絞る（エッジの源泉）
  2. base_rates — 物語より先にベースレートを置く（過大な確率の抑制）
  3. forecast   — 買う前に反証可能な確率を書き、改変不能な台帳に記録する
     calibration — 確率の当て具合を測る。アルファより遥かに速く測定できる
  4. sizing     — 実測キャリブレーションでゲートしたケリー基準で賭け金を決める

加えて validation は、バックテストが過剰最適化かどうかを定量化する。
標準ライブラリのみで動作する（numpy / pandas 不要）。
"""

